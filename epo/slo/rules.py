"""Prometheus rules and a Grafana dashboard, generated from config/slo.yaml so the alerts that page are the ones the
evaluation measured. `python -m epo.eval.cli rules` writes them; CI checks they are current and runs promtool."""
from __future__ import annotations

import json

import yaml

from epo.slo.alerts import WINDOWS


def rules(slo: dict) -> dict:
    groups = []
    for s in slo["slos"]:
        name, bad, total, objective = s["name"], s["bad"], s["total"], s["objective"]
        rec = [{"record": f"slo:{name}:budget_per_minute",
                "expr": f"sum(increase({total}[1d])) / 1440 * {1 - objective:g}"}]
        alerts = []
        for long, short, burn in WINDOWS:
            for w in (long, short):
                if not any(r["record"] == f"slo:{name}:bad_{w}m" for r in rec):
                    rec.append({"record": f"slo:{name}:bad_{w}m", "expr": f"sum(increase({bad}[{w}m]))"})
            alerts.append({
                "alert": f"{name.title().replace('_', '')}BudgetBurn{long}m",
                "expr": (f"slo:{name}:bad_{long}m > {burn:g} * {long} * slo:{name}:budget_per_minute and "
                         f"slo:{name}:bad_{short}m > {burn:g} * {short} * slo:{name}:budget_per_minute"),
                "labels": {"severity": "page", "slo": name, "service": s["service"]},
                "annotations": {"summary": f"{name}: error budget burning at {burn:g}x over {long}m",
                                "runbook_url": f"https://github.com/manojrevenkar12-web/equity-platform-ops/blob/main/docs/runbooks/{name}.md"},
            })
        alerts.append({"alert": f"{name.title().replace('_', '')}SlowBurn", "expr": (
            f"sum(increase({bad}[3d])) > 1 * 4320 * slo:{name}:budget_per_minute"),
            "labels": {"severity": "ticket", "slo": name, "service": s["service"]},
            "annotations": {"summary": f"{name}: budget spent at the rate it accrues over 3 days"}})
        groups.append({"name": f"slo-{name}", "rules": rec + alerts})
    for sym in slo["symptoms"]:
        groups.append({"name": f"symptom-{sym['name']}", "rules": [{
            "alert": sym["name"], "expr": sym["expr"], "for": sym["for"], "labels": {"severity": "ticket"},
            "annotations": {"summary": sym["summary"]}}]})
    return {"groups": groups}


def alertmanager_routes() -> dict:
    """Pages to PagerDuty, grouped per service so a burst becomes one incident; tickets to a channel."""
    return {"route": {"receiver": "tickets", "group_by": ["service"], "group_wait": "30s", "group_interval": "30m",
                      "routes": [{"matchers": ['severity="page"'], "receiver": "pagerduty", "group_by": ["service"]}]},
            "receivers": [{"name": "pagerduty", "pagerduty_configs": [{"routing_key": "${PAGERDUTY_ROUTING_KEY}"}]},
                          {"name": "tickets", "webhook_configs": [{"url": "${TICKET_WEBHOOK_URL}"}]}]}


def grafana(slo: dict) -> dict:
    panels = []
    for i, s in enumerate(slo["slos"]):
        n = s["name"]
        panels.append({"type": "stat", "title": f"{n}: budget left this month", "gridPos": {"x": 0, "y": i * 8, "w": 8, "h": 8},
                       "targets": [{"expr": f"1 - sum(increase({s['bad']}[30d])) / (sum(increase({s['total']}[30d])) * {1 - s['objective']:g})"}],
                       "fieldConfig": {"defaults": {"unit": "percentunit", "min": 0, "max": 1}}})
        panels.append({"type": "timeseries", "title": f"{n}: burn rate (1h and 6h)", "gridPos": {"x": 8, "y": i * 8, "w": 16, "h": 8},
                       "targets": [{"expr": f"slo:{n}:bad_{w}m / ({w} * slo:{n}:budget_per_minute)", "legendFormat": f"{w}m"}
                                   for w in (60, 360)]})
    return {"title": "Equity platform SLOs", "uid": "epo-slos", "schemaVersion": 39, "panels": panels,
            "tags": ["slo", "generated"], "time": {"from": "now-7d", "to": "now"}}


def dump(obj: dict) -> str:
    return "# Generated by `python -m epo.eval.cli rules` from config/slo.yaml. Do not edit.\n" + yaml.safe_dump(obj, sort_keys=False)


def dump_json(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"
